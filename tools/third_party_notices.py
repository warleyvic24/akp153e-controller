"""Gera THIRD_PARTY_NOTICES.md com os textos de licença das dependências que entram no executável.

Uso (na raiz do projeto, depois de `cargo fetch`):  python tools/third_party_notices.py

Lê `cargo metadata` para o alvo Windows, pega os arquivos LICENSE de cada crate e agrupa os textos
idênticos, listando quais crates os usam. Crates sem arquivo de licença aparecem numa lista à parte,
com a licença declarada no Cargo.toml.
"""
import hashlib
import json
import pathlib
import subprocess

TARGET = "x86_64-pc-windows-msvc"
OUTPUT = pathlib.Path("THIRD_PARTY_NOTICES.md")
LICENSE_PREFIXES = ("license", "licence", "copying", "unlicense", "notice")
# Pastas com licenças de arquivos embutidos: `epaint_default_fonts` guarda as das fontes em `fonts/`.
EXTRA_LICENSE_DIRS = ("fonts",)

HEADER = """# Third-party notices

This program is built with the open-source crates listed below. Each section gives a license text
and the crates that are distributed under it. Generated by `tools/third_party_notices.py`; do not
edit by hand.

Some crates offer a choice of licenses (for example `MIT OR Apache-2.0`); they are used here under
the permissive option. The egui default fonts include components under the SIL Open Font License 1.1
and the Ubuntu Font Licence 1.0; their texts are included below.
"""


def metadata() -> dict:
    out = subprocess.check_output(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", TARGET]
    )
    return json.loads(out)


def used_packages(meta: dict) -> list[dict]:
    root = set(meta["workspace_members"])
    used = {n["id"] for n in meta["resolve"]["nodes"]} - root
    return sorted((p for p in meta["packages"] if p["id"] in used), key=lambda p: (p["name"], p["version"]))


def license_files(package: dict) -> list[pathlib.Path]:
    """Arquivos de licença na raiz do crate e os `.txt` de pastas conhecidas (ex.: as fontes do egui)."""
    folder = pathlib.Path(package["manifest_path"]).parent
    found = [
        f for f in folder.iterdir() if f.is_file() and f.name.lower().startswith(LICENSE_PREFIXES)
    ]
    for extra in EXTRA_LICENSE_DIRS:
        found.extend((folder / extra).glob("*.txt"))
    return sorted(found)


def main() -> None:
    texts = {}
    missing = []
    for package in used_packages(metadata()):
        label = f"{package['name']} {package['version']}"
        files = license_files(package)
        if not files:
            missing.append((label, package.get("license") or "unknown"))
        for f in files:
            text = f.read_text(encoding="utf-8", errors="replace").strip()
            key = hashlib.sha256(" ".join(text.split()).encode()).hexdigest()
            entry = texts.setdefault(key, {"text": text, "crates": set()})
            entry["crates"].add(label)

    parts = [HEADER]
    for n, entry in enumerate(sorted(texts.values(), key=lambda e: sorted(e["crates"])[0]), 1):
        crates = ", ".join(sorted(entry["crates"]))
        parts.append(f"\n## License text {n}\n\nUsed by: {crates}\n\n```text\n{entry['text']}\n```\n")
    if missing:
        parts.append("\n## Crates without a license file in their package\n")
        parts.append("\nThe license below is the one declared in each crate's `Cargo.toml`.\n\n")
        parts.extend(f"- {label}: {lic}\n" for label, lic in missing)
    OUTPUT.write_text("".join(parts), encoding="utf-8", newline="\n")
    print(f"{OUTPUT}: {len(texts)} license texts, {len(missing)} crates without a file")


if __name__ == "__main__":
    main()
